// AgentsFile is the instructions file Codex and other agents read at the
// workspace root. hc owns only the block between the markers in it.
const AgentsFile = "AGENTS.md"

const (
	beginMarker = "<!-- hc:begin -->"
	endMarker   = "<!-- hc:end -->"
	// legacyHeader starts the AGENTS.md hc generated before it kept to a
	// block; such a file is hc's entirely and is replaced by the block.
	legacyHeader = "<!-- Generated by hc."
)

// Index returns the block hc writes into AGENTS.md of a workspace of the
// context at root. A practice workspace gets a guide for agents helping the
// user practice, with the managed skills installed there as one section of
// it, and gets it whether or not any is. A pack checkout, whose own text is
// outside the block, gets only the skill index, or "" without skills.
func Index(root string, ctx Context) string {
	skills := skillLines(root)
	if ctx == Practice {
		return practiceBlock(skills)
	}
	if skills == "" {
		return ""
	}
	return beginMarker + `
## hc skills

This is a handcoding (hc) workspace. Before you work on a task one of these
skills covers, read its SKILL.md and follow it:

` + skills + `

` + scratchRule + `

hc rewrites this block when it installs skills; write your own notes outside it.
` + endMarker
}

// skillLines lists the managed skills installed at root, one Markdown list
// item each, or returns "" when there are none.
func skillLines(root string) string {
	var lines []string
	for _, s := range All() {
		for _, dir := range []string{AgentsDir, ClaudeDir} {
			if in := inspect(root, path.Join(dir, s.Name)); in.State.Managed() {
				lines = append(lines, fmt.Sprintf("- `%s`: %s Read `%s`.", s.Name, oneLine(s.Description), path.Join(in.Dir, MainFile)))
				break
			}
		}
	}
	return strings.Join(lines, "\n")
}

// scratchRule keeps agents working on different problems at once apart.
const scratchRule = `Keep throwaway files (scripts, scratch data) in .hc/scratch/<slug>/, the
directory of the problem you work on (.hc/scratch/ for other work): other
agents may be working on other problems at the same time, with files of the
same names. .hc/ is hc's own directory, never part of a pack. Delete your
files when you are done.`

// practiceGuide is the template of a practice workspace's block.
var practiceGuide = template.Must(template.New("practice").Delims("<%", "%>").Parse(builtin.PracticeGuide()))

// practiceBlock is the block of a practice workspace. Only its skills
// section depends on the workspace, so installing a pack leaves it as it is.
func practiceBlock(skills string) string {
	var b strings.Builder
	b.WriteString(beginMarker + "\n")
	data := struct{ Skills, Scratch string }{skills, scratchRule}
	if err := practiceGuide.Execute(&b, data); err != nil {
		// The embedded template is checked by tests; this is a build defect.
		panic(err)
	}
	b.WriteString(endMarker)
	return b.String()
}

// ClaudeFile is the instructions file Claude Code reads at the workspace
// root. Claude Code does not read AGENTS.md itself, so hc creates one that
// imports it.
const ClaudeFile = "CLAUDE.md"

// claudeImport is the CLAUDE.md hc creates.
const claudeImport = "@AGENTS.md\n"

// WriteClaudeFile creates CLAUDE.md at root, importing AGENTS.md, when root
// has AGENTS.md and Claude Code has no instructions file there (CLAUDE.md
// or .claude/CLAUDE.md). One that exists is the user's, and hc never touches
// it. It reports whether it created the file.
func WriteClaudeFile(root string) (bool, error) {
	for _, p := range []string{ClaudeFile, filepath.Join(".claude", ClaudeFile)} {
		if _, err := os.Lstat(filepath.Join(root, p)); err == nil || !errors.Is(err, os.ErrNotExist) {
			return false, err
		}
	}
	if _, err := os.Stat(filepath.Join(root, AgentsFile)); err != nil {
		if errors.Is(err, os.ErrNotExist) {
			err = nil
		}
		return false, err
	}
	return true, os.WriteFile(filepath.Join(root, ClaudeFile), []byte(claudeImport), 0o644)
}

func oneLine(s string) string { return strings.Join(strings.Fields(s), " ") }

// WriteIndex writes the block of a workspace of the context into AGENTS.md
// at root (see Index), keeping the rest of the file: it creates the file,
// appends the block, replaces it in place, or removes it when the context
// gets none. It reports whether the file changed.
func WriteIndex(root string, ctx Context) (bool, error) {
	file := filepath.Join(root, AgentsFile)
	data, err := os.ReadFile(file)
	if err != nil && !errors.Is(err, os.ErrNotExist) {
		return false, err
	}
	old := string(data)
	updated, err := withIndex(old, Index(root, ctx))
	if err != nil || updated == old {
		return false, err
	}
	return true, os.WriteFile(file, []byte(updated), 0o644)
}

// withIndex returns content with its hc block replaced by block, or removed
// when block is "".
func withIndex(content, block string) (string, error) {
	begin := strings.Index(content, beginMarker)
	if begin < 0 {
		switch {
		case block == "":
			return content, nil
		case content == "" || strings.HasPrefix(content, legacyHeader):
			return block + "\n", nil
		}
		return strings.TrimRight(content, "\n") + "\n\n" + block + "\n", nil
	}
	end := strings.Index(content[begin:], endMarker)
	if end < 0 {
		return "", fmt.Errorf("%s: %s without %s", AgentsFile, beginMarker, endMarker)
	}
	end += begin + len(endMarker)
	if block == "" {
		// Take the line break after the block with it.
		end += len(content[end:]) - len(strings.TrimPrefix(content[end:], "\n"))
	}
	return content[:begin] + block + content[end:], nil
}
