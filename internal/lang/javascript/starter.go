func jsType(t string) string {
	base, depth := problem.SplitArray(t)
	s := map[string]string{"integer": "number", "long": "number", "double": "number", "boolean": "boolean", "string": "string", "character": "string", "void": "void"}[base]
	if s == "" {
		s = base
	}
	if problem.IsNodeVariant(base) {
		s = "_Node"
	}
	if depth > 0 {
		return s + strings.Repeat("[]", depth)
	}
	if problem.IsNodeVariant(base) || base == "ListNode" || base == "TreeNode" {
		return s + " | null"
	}
	return s
}
func (l Language) params(ps []problem.Param) string {
	out := []string{}
	for _, p := range ps {
		s := p.Name
		if l.TypeScript {
			s += ": " + jsType(p.Type)
		}
		out = append(out, s)
	}
	return strings.Join(out, ", ")
}
func (l Language) Starter(p *problem.Problem) (string, error) {
	if b, e := os.ReadFile(filepath.Join(p.Dir, "templates", l.SolutionFile())); e == nil {
		return string(b), nil
	} else if !os.IsNotExist(e) {
		return "", e
	}
	var s strings.Builder
	ret := func(t string) string {
		if l.TypeScript {
			return ": " + jsType(t)
		}
		return ""
	}
	if p.Kind == problem.KindFunction {
		f := p.Function
		fmt.Fprintf(&s, "function %s(%s)%s {\n    throw new Error('not implemented');\n}\n", f.Name, l.params(f.Params), ret(f.Returns))
	} else {
		c := p.Class
		fmt.Fprintf(&s, "class %s {\n    constructor(%s) { }\n", c.Name, l.params(c.Constructor))
		for _, m := range c.Methods {
			fmt.Fprintf(&s, "    %s(%s)%s { throw new Error('not implemented'); }\n", m.Name, l.params(m.Params), ret(m.Returns))
		}
		s.WriteString("}\n")
	}
	return s.String(), nil
}
func declarations(p *problem.Problem, rt string) string {
	s := `// Generated by hc. Judge types and LeetCode libraries, not solution code.
declare class ListNode { val: number; next: ListNode | null; constructor(val?: number, next?: ListNode | null); }
declare class TreeNode { val: number; left: TreeNode | null; right: TreeNode | null; constructor(val?: number, left?: TreeNode | null, right?: TreeNode | null); }
declare class NestedInteger { constructor(value?: number); isInteger(): boolean; getInteger(): number | null; setInteger(value: number): void; add(value: NestedInteger): void; getList(): NestedInteger[]; }
declare class Employee { id: number; importance: number; subordinates: number[]; constructor(id?: number, importance?: number, subordinates?: number[]); }
`
	node := map[string]string{
		"GraphNode":      "val: number; neighbors: _Node[]; constructor(val?: number, neighbors?: _Node[]);",
		"NaryNode":       "val: number; children: _Node[]; constructor(val?: number, children?: _Node[]);",
		"RandomListNode": "val: number; next: _Node | null; random: _Node | null; constructor(val?: number, next?: _Node | null, random?: _Node | null);",
		"NextTreeNode":   "val: number; left: _Node | null; right: _Node | null; next: _Node | null; constructor(val?: number, left?: _Node | null, right?: _Node | null, next?: _Node | null);",
		"QuadNode":       "val: boolean; isLeaf: boolean; topLeft: _Node | null; topRight: _Node | null; bottomLeft: _Node | null; bottomRight: _Node | null; constructor(val?: boolean, isLeaf?: boolean, topLeft?: _Node | null, topRight?: _Node | null, bottomLeft?: _Node | null, bottomRight?: _Node | null);",
		"MultilevelNode": "val: number; prev: _Node | null; next: _Node | null; child: _Node | null; constructor(val?: number, prev?: _Node | null, next?: _Node | null, child?: _Node | null);",
	}[p.NodeVariant()]
	if node != "" {
		s += "declare class _Node { " + node + " }\ndeclare const Node: typeof _Node;\ntype Node = _Node;\n"
	}
	// Import types without turning this declaration file into a module.
	for _, pkg := range []string{"heap", "priority-queue", "queue", "deque", "stack", "linked-list", "set"} {
		names := map[string][]string{"heap": {"Heap", "MinHeap", "MaxHeap"}, "priority-queue": {"PriorityQueue", "MinPriorityQueue", "MaxPriorityQueue"}, "queue": {"Queue"}, "deque": {"Deque"}, "stack": {"Stack"}, "linked-list": {"LinkedList", "DoublyLinkedList", "LinkedListNode", "DoublyLinkedListNode"}, "set": {"EnhancedSet"}}[pkg]
		for _, name := range names {
			path := filepath.ToSlash(filepath.Join(rt, "node_modules", "@datastructures-js", pkg))
			fmtS := fmt.Sprintf("declare const %s: typeof import(%q).%s;\ntype %s<T = any> = import(%q).%s<T>;\n", name, path, name, name, path, name)
			s += fmtS
		}
	}
	s += fmt.Sprintf("declare const _: typeof import(%q);\n", filepath.ToSlash(filepath.Join(rt, "node_modules", "@types", "lodash")))
	return s
}
