func envFile(t *testing.T, path, content string, mode os.FileMode) {
	t.Helper()
	if err := os.MkdirAll(filepath.Dir(path), 0755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(path, []byte(content), mode); err != nil {
		t.Fatal(err)
	}
}
func fakeEnvironment(t *testing.T) (Language, string, string) {
	t.Helper()
	root := t.TempDir()
	fixture := filepath.Join(root, "fixture")
	b, _ := files.ReadFile("dependencies/package-lock.json")
	var lock struct {
		Packages map[string]struct{ Version string }
	}
	if err := json.Unmarshal(b, &lock); err != nil {
		t.Fatal(err)
	}
	for path, pkg := range lock.Packages {
		if path != "" {
			envFile(t, filepath.Join(fixture, path, "package.json"), fmt.Sprintf(`{"version":%q}`, pkg.Version), 0644)
		}
	}
	envFile(t, filepath.Join(fixture, "node_modules/lodash/lodash.js"), "module.exports = {};", 0644)
	node, npm := filepath.Join(root, "tools/node"), filepath.Join(root, "tools/npm")
	envFile(t, node, "#!/bin/sh\necho v22.0.0\n", 0755)
	// Paths generated by t.TempDir contain no shell metacharacters.
	script := fmt.Sprintf(`#!/bin/sh
set -eu
[ "$*" = 'ci --ignore-scripts --no-audit --no-fund --prefer-offline' ]
echo install >> '%s/visits'
[ ! -f '%s/fail' ] || exit 1
cp -R '%s/node_modules' .
`, root, root, fixture)
	envFile(t, npm, script, 0755)
	return Language{Node: node, NPM: npm, Environment: filepath.Join(root, ".hc/node")}, root, script
}
func TestEnvironmentLifecycle(t *testing.T) {
	t.Parallel()
	l, root, script := fakeEnvironment(t)
	var wg sync.WaitGroup
	errs := make(chan error, 4)
	for range 4 {
		wg.Go(func() { errs <- l.Setup(context.Background(), io.Discard) })
	}
	wg.Wait()
	close(errs)
	for err := range errs {
		if err != nil {
			t.Fatal(err)
		}
	}
	visits, _ := os.ReadFile(filepath.Join(root, "visits"))
	if string(visits) != "install\n" || !l.EnvironmentReady() {
		t.Fatalf("concurrent setup: %s", visits)
	}
	if err := os.Remove(l.NPM); err != nil {
		t.Fatal(err)
	}
	if err := l.Setup(context.Background(), io.Discard); err != nil {
		t.Fatalf("ready environment invoked npm: %v", err)
	}
	// A failed rebuild must not damage a usable installation.
	envFile(t, l.NPM, script, 0755)
	envFile(t, filepath.Join(root, "fail"), "", 0644)
	if err := l.SyncEnvironment(context.Background(), io.Discard); err == nil {
		t.Fatal("failed npm accepted")
	}
	if !l.EnvironmentReady() {
		t.Fatal("failed rebuild destroyed environment")
	}
	if err := os.Remove(filepath.Join(root, "fail")); err != nil {
		t.Fatal(err)
	}
	// Detect missing files and repair from a clean install, retaining other versions.
	file := filepath.Join(l.environment(""), "node_modules/lodash/lodash.js")
	if err := os.Remove(file); err != nil {
		t.Fatal(err)
	}
	if l.EnvironmentReady() {
		t.Fatal("partial environment reported ready")
	}
	envFile(t, filepath.Join(l.Environment, "old-lock/keep"), "old", 0644)
	if err := l.Setup(context.Background(), io.Discard); err != nil {
		t.Fatal(err)
	}
	if !l.EnvironmentReady() {
		t.Fatal("repair incomplete")
	}
	if _, err := os.Stat(filepath.Join(l.Environment, "old-lock/keep")); err != nil {
		t.Fatal(err)
	}
	entries, _ := os.ReadDir(l.Environment)
	for _, e := range entries {
		if strings.HasPrefix(e.Name(), ".install-") {
			t.Fatal("left staging directory")
		}
	}
}
func TestEnvironmentFailedFirstInstallAndCancellation(t *testing.T) {
	t.Parallel()
	l, root, _ := fakeEnvironment(t)
	envFile(t, filepath.Join(root, "fail"), "", 0644)
	if err := l.Setup(context.Background(), io.Discard); err == nil {
		t.Fatal("failed install accepted")
	}
	if l.EnvironmentReady() {
		t.Fatal("failed installation marked ready")
	}
	if _, err := os.Stat(l.environment("")); !os.IsNotExist(err) {
		t.Fatal("published incomplete environment")
	}
	ctx, cancel := context.WithCancel(context.Background())
	cancel()
	if err := l.Setup(ctx, io.Discard); err == nil {
		t.Fatal("cancelled install accepted")
	}
}
func TestEnvironmentDiagnosisReadOnly(t *testing.T) {
	t.Parallel()
	l, root, _ := fakeEnvironment(t)
	var progress bytes.Buffer
	before, _ := os.ReadDir(root)
	checks := l.diagnoseEnvironment(context.Background())
	after, _ := os.ReadDir(root)
	if len(before) != len(after) || checks[0].Status != "uninitialized" {
		t.Fatal(checks)
	}
	if _, err := os.Stat(l.Environment); !os.IsNotExist(err) {
		t.Fatal("doctor created environment")
	}
	if err := l.Setup(context.Background(), &progress); err != nil {
		t.Fatal(err)
	}
	stamp, err := os.Stat(filepath.Join(l.environment(""), ".complete.json"))
	if err != nil {
		t.Fatal(err)
	}
	checks = l.diagnoseEnvironment(context.Background())
	afterStamp, _ := os.Stat(filepath.Join(l.environment(""), ".complete.json"))
	if len(checks) != 1 || checks[0].Status != "ok" || !stamp.ModTime().Equal(afterStamp.ModTime()) {
		t.Fatal(checks)
	}
}
func TestEnvironmentLockCancellation(t *testing.T) {
	t.Parallel()
	l, root, _ := fakeEnvironment(t)
	// Keep npm running long enough for another caller to wait on the file lock.
	script := fmt.Sprintf("#!/bin/sh\ntouch '%s/started'\nsleep 2\nexit 1\n", root)
	envFile(t, l.NPM, script, 0755)
	done := make(chan error, 1)
	go func() { done <- l.Setup(context.Background(), io.Discard) }()
	deadline := time.Now().Add(3 * time.Second)
	for {
		if _, err := os.Stat(filepath.Join(root, "started")); err == nil {
			break
		}
		if time.Now().After(deadline) {
			t.Fatal("installer did not start")
		}
		time.Sleep(10 * time.Millisecond)
	}
	ctx, cancel := context.WithTimeout(context.Background(), 50*time.Millisecond)
	defer cancel()
	if err := l.Setup(ctx, io.Discard); !errors.Is(err, context.DeadlineExceeded) {
		t.Fatalf("lock cancellation: %v", err)
	}
	if err := <-done; err == nil {
		t.Fatal("failed installer accepted")
	}
}

// Third-party package contents must never become part of the hc binary again.
func TestEmbeddedAssetsContainNoDependencies(t *testing.T) {
	t.Parallel()
	err := fs.WalkDir(files, ".", func(path string, d fs.DirEntry, err error) error {
		if err != nil || d.IsDir() {
			return err
		}
		if path == "dependencies/package.json" || path == "dependencies/package-lock.json" || strings.HasPrefix(path, "runtime/") && strings.HasSuffix(path, ".cjs") {
			return nil
		}
		return fmt.Errorf("unexpected embedded asset: %s", path)
	})
	if err != nil {
		t.Fatal(err)
	}
}
