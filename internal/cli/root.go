type rootOptions struct {
	workspace string
}

// Execute runs the CLI.
func Execute(ctx context.Context) error {
	return newRootCmd().ExecuteContext(ctx)
}

func newRootCmd() *cobra.Command {
	opts := &rootOptions{}
	root := &cobra.Command{
		Use:   "hc",
		Short: "handcoding — practice LeetCode-style problems locally",
		Long: `handcoding (hc) is a local judge for LeetCode-style problems.

Write solutions in your own editor, then test, submit and debug them locally,
offline, with your own debugger. Problems come from LeetCode (hc fetch), your
own files (hc new, hc import) or packs installed in the workspace, and test
cases can be generated by a coding agent (hc gen).

A problem is named by its slug, id, directory name or a unique slug prefix,
or as <pack>/<ref> within one pack: local/two-sum.

Run hc with no arguments to open the interactive problem list.`,
		Version:       version.String(),
		SilenceUsage:  true,
		SilenceErrors: true,
		RunE: func(cmd *cobra.Command, args []string) error {
			return runList(cmd, opts, listOptions{})
		},
	}
	root.PersistentFlags().StringVarP(&opts.workspace, "workspace", "w", "", "workspace directory (default: $HC_WORKSPACE, nearest hc.yaml or pack.yaml, ~/handcoding)")

	root.AddGroup(
		&cobra.Group{ID: "practice", Title: "Practice:"},
		&cobra.Group{ID: "bank", Title: "Problems:"},
		&cobra.Group{ID: "agent", Title: "Coding agent:"},
	)
	add := func(group string, cmds ...*cobra.Command) {
		for _, c := range cmds {
			c.GroupID = group
			root.AddCommand(c)
		}
	}
	add("practice",
		newListCmd(opts),
		newStartCmd(opts),
		newEditCmd(opts),
		newShowCmd(opts),
		newTestCmd(opts),
		newSubmitCmd(opts),
		newDebugCmd(opts),
		newResetCmd(opts),
		newDiscardCmd(opts),
		newHistoryCmd(opts),
		newEnvCmd(opts),
	)
	add("bank",
		newInitCmd(opts),
		newFetchCmd(opts),
		newNewCmd(opts),
		newImportCmd(opts),
		newCasesCmd(opts),
		newValidateCmd(opts),
		newPackCmd(opts),
		newDocsCmd(opts),
	)
	add("agent",
		newGenCmd(opts),
		newFixCmd(opts),
		newSkillCmd(opts),
	)
	return root
}

// openApp opens the workspace and the application.
func (o *rootOptions) openApp() (*app.App, error) {
	ws, err := workspace.Find(o.workspace)
	if err != nil {
		return nil, err
	}
	return app.New(ws), nil
}

// withProblem opens the app and resolves the problem and language.
func (o *rootOptions) withProblem(ref, langName string, fn func(a *app.App, p *problem.Problem, l lang.Language) error) error {
	a, err := o.openApp()
	if err != nil {
		return err
	}
	defer a.Close()
	p, err := a.WS.Problem(ref)
	if err != nil {
		return err
	}
	l, note, err := a.SolutionLang(p, langName)
	if err != nil {
		return err
	}
	if note != "" {
		fmt.Fprintln(os.Stderr, ui.Faint.Render("note: "+note))
	}
	return fn(a, p, l)
}

// withProblemOnly opens the app and resolves the problem.
func withProblemOnly(root *rootOptions, ref string, fn func(a *app.App, p *problem.Problem) error) error {
	a, err := root.openApp()
	if err != nil {
		return err
	}
	defer a.Close()
	p, err := a.WS.Problem(ref)
	if err != nil {
		return err
	}
	return fn(a, p)
}

// withWritableProblem is withProblemOnly for commands that change the
// problem, which installed packs refuse.
func withWritableProblem(root *rootOptions, ref string, fn func(a *app.App, p *problem.Problem) error) error {
	return withProblemOnly(root, ref, func(a *app.App, p *problem.Problem) error {
		if err := a.WS.CheckWritable(p); err != nil {
			return err
		}
		return fn(a, p)
	})
}

func isTerminal(f *os.File) bool {
	return isatty.IsTerminal(f.Fd()) || isatty.IsCygwinTerminal(f.Fd())
}

// editorCommand builds the command that opens path in the user's editor.
func editorCommand(cfg workspace.Config, path string) (*exec.Cmd, error) {
	editor := cfg.Editor
	for _, env := range []string{"VISUAL", "EDITOR"} {
		if editor == "" {
			editor = os.Getenv(env)
		}
	}
	if editor == "" {
		editor = "vi"
	}
	parts := strings.Fields(editor)
	if len(parts) == 0 {
		return nil, errors.New("empty editor command")
	}
	cmd := exec.Command(parts[0], append(parts[1:], path)...)
	cmd.Stdin, cmd.Stdout, cmd.Stderr = os.Stdin, os.Stdout, os.Stderr
	return cmd, nil
}

// pause waits for Enter; used when a command runs inside the TUI.
func pause() {
	fmt.Fprint(os.Stderr, "\nPress Enter to return…")
	_, _ = bufio.NewReader(os.Stdin).ReadString('\n')
}

// confirm asks a yes/no question on the terminal.
func confirm(question string) bool {
	if !isTerminal(os.Stdin) {
		return false
	}
	fmt.Fprintf(os.Stderr, "%s [y/N] ", question)
	line, _ := bufio.NewReader(os.Stdin).ReadString('\n')
	switch strings.ToLower(strings.TrimSpace(line)) {
	case "y", "yes":
		return true
	}
	return false
}

// langFlag registers the common --lang flag.
func langFlag(cmd *cobra.Command, target *string) {
	cmd.Flags().StringVarP(target, "lang", "l", "", "language (go, python); default from hc.yaml")
}
